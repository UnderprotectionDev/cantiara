/**
 * Link Sharing behavior (spec 73, #482). The closed world is built only from
 * what the source port hands over for the chosen root: the root record, the
 * members a collection root names, and the parts of those records. Nothing is
 * inherited through a folder, parent, relation or view. Approval re-derives
 * the preview, checks the founder's explicit selection against it and writes
 * one immutable manifest revision through the store.
 */

export interface ShareSourceField {
  key: string;
  kind: ShareFieldKind;
  label: string;
  value: string | null;
}

/** A non-field part of a record: version, attachment, embed, relation, layout. */
export interface ShareSourcePart {
  detail: string | null;
  /** Exactly one part of a group must be approved (a version, a view). */
  group?: string;
  id: string;
  kind: Exclude<ShareItemKind, "Field" | "Record">;
  label: string;
  /** A relation's other end; approvable only when that record is itself in scope. */
  target?: { id: string; kind: string };
}

export interface ShareSourceRecord {
  fields: ShareSourceField[];
  id: string;
  /** A main record kind; anything else (an Inbox item, a Draft) is dropped. */
  kind: string;
  parts: ShareSourcePart[];
  title: string;
}

export interface ShareSourceMember {
  /** Whether the record belongs to the collection filter for these values. */
  matchesFilter: (values: Record<string, string | null>) => boolean;
  record: ShareSourceRecord;
}

export interface ShareSource {
  /** Reasons no link can be approved yet, such as no exact version to pick. */
  blockers: string[];
  /** Filter pool of a collection root; empty for every other root. */
  members: ShareSourceMember[];
  projectId: string;
  record: ShareSourceRecord;
}

export interface StoredShareSurface {
  approvedAt: string;
  /** The optional Bağlantı süre dolumu; `null` is none. */
  expiresAt: Date | null;
  manifest: ShareManifest;
  passwordProtected: boolean;
  revision: number;
  surfaceId: string;
}

export interface ShareApprovalCommit {
  accountId: string;
  approvalId: string;
  fingerprint: string;
  manifest: ShareManifest;
  /** Generated by the behavior so memory and database stores agree. */
  newSurfaceId: string;
  placeholdersAcknowledged: boolean;
  projectId: string;
  root: ShareRoot;
  /** `null` creates the Dış yüzey; otherwise a revision joins that surface. */
  surfaceId: string | null;
  /** SHA-256 of the token minted with a new surface; `null` for a new revision. */
  tokenHash: string | null;
}

export interface ShareAccessPatch {
  /** `undefined` keeps it; `null` removes it. */
  passwordHash?: string | null;
  tokenHash?: string;
}

/** A secret-free event for the irreversible security log (ADR-0003, ADR-0019). */
export interface ShareAccessEvent {
  accessEpoch: number;
  actor: string;
  occurredAt: Date;
  surfaceId: string;
  type:
    | "link-sharing.password-changed"
    | "link-sharing.token-rotated"
    | "link-sharing.surface-revoked"
    | "link-sharing.sessions-revoked";
}

export interface LinkSharingSecurityEvents {
  append: (event: ShareAccessEvent) => Promise<void>;
  /** Every Link Sharing event in the log, oldest first (restore replay). */
  list: () => Promise<ShareAccessEvent[]>;
}

/** What an owned, not revoked Link Sharing surface looks like to a lifecycle write. */
export interface ShareLifecycleState {
  /** The epoch before the next access change bumps it by one. */
  accessEpoch: number;
  expiresAt: Date | null;
  passwordProtected: boolean;
}

export interface ShareReshareCommit {
  accountId: string;
  expiresAt: Date | null;
  newSurfaceId: string;
  /** The expired surface the new one copies; it stays expired and reopenable. */
  sourceSurfaceId: string;
  tokenHash: string;
}

/** Port to the source records and the stored surfaces; no member rewrites a revision. */
export interface LinkSharingStore {
  commit: (commit: ShareApprovalCommit) => Promise<ApprovedShare | null>;
  findApproval: (
    accountId: string,
    approvalId: string,
  ) => Promise<{ fingerprint: string; result: ApprovedShare } | null>;
  /** Expiry and password state of the owned, not revoked surface. */
  lifecycle: (
    accountId: string,
    surfaceId: string,
  ) => Promise<ShareLifecycleState | null>;
  /**
   * A new Dış yüzey copying the expired one's latest approved revision (and
   * its password hash) under a new token. A repeated `newSurfaceId` returns
   * the same surface with `accessToken: null`.
   */
  reshare: (
    commit: ShareReshareCommit,
  ) => Promise<{ created: boolean; share: ApprovedShare } | null>;
  /** Terminal `Bağlantı iptali`: sets the cancellation, ends every session. */
  revoke: (
    accountId: string,
    surfaceId: string,
    at: Date,
  ) => Promise<{ accessEpoch: number } | null>;
  roots: (
    accountId: string,
    projectId: string,
  ) => Promise<ShareRootSummary[] | null>;
  source: (accountId: string, root: ShareRoot) => Promise<ShareSource | null>;
  /** The given surface of the root, else its latest uncancelled one. */
  surface: (
    accountId: string,
    root: ShareRoot,
    surfaceId?: string,
  ) => Promise<StoredShareSurface | null>;
  /** The owned, uncancelled Link Sharing surface gets the patch and a new access epoch. */
  updateAccess: (
    accountId: string,
    surfaceId: string,
    patch: ShareAccessPatch,
  ) => Promise<{ accessEpoch: number; passwordProtected: boolean } | null>;
  /**
   * Sets the expiry of the owned, not revoked surface; `endSessions` also
   * bumps the access epoch so sessions minted before it stay dead.
   */
  updateExpiry: (
    accountId: string,
    surfaceId: string,
    expiresAt: Date | null,
    endSessions: boolean,
  ) => Promise<{ accessEpoch: number } | null>;
}

interface ScopeModel {
  /** Field item id to its field key. */
  fieldKeys: Map<string, string>;
  items: ShareItem[];
  /** Relation item id to the Record item id it points at, when in scope. */
  relationTargets: Map<string, string>;
}

const ROOT_KINDS = new Set<string>(LINK_SHARING_ROOT_KINDS);
const recordItemId = (record: ShareSourceRecord) =>
  `record:${record.kind}:${record.id}`;
const fieldItemId = (record: ShareSourceRecord, key: string) =>
  `field:${record.kind}:${record.id}:${key}`;
const partItemId = (record: ShareSourceRecord, part: ShareSourcePart) =>
  `part:${record.kind}:${record.id}:${part.id}`;

function fieldsOf(record: ShareSourceRecord): ShareSourceField[] {
  const fields = record.fields.filter((field) => !isSecretKind(field.kind));
  return fields.some((field) => field.key === "title")
    ? fields
    : [
        { key: "title", kind: "title", label: "Title", value: record.title },
        ...fields,
      ];
}

/**
 * Values the visitor would see for these fields now: frozen fields keep their
 * approved value, `Live` fields follow the source. Used for membership only.
 */
function approvedViewValues(
  record: ShareSourceRecord,
  previous: Map<string, ShareManifestItem>,
) {
  const values: Record<string, string | null> = {};
  for (const field of fieldsOf(record)) {
    const approved = previous.get(fieldItemId(record, field.key));
    values[field.key] =
      approved && !approved.live ? approved.value : field.value;
  }
  return values;
}

function currentValues(record: ShareSourceRecord) {
  return Object.fromEntries(
    fieldsOf(record).map((field) => [field.key, field.value]),
  );
}

interface ListedRecord {
  candidate: boolean;
  leavesScope: boolean;
  record: ShareSourceRecord;
}

/**
 * A new filter match is only a candidate on the owner's diff. An approved
 * member leaves only when the values the visitor sees (frozen, with `Live`
 * fields current) no longer match; any other edit never shrinks the scope.
 */
function listRecords(
  source: ShareSource,
  previous: Map<string, ShareManifestItem> | null,
): ListedRecord[] {
  const root: ListedRecord = {
    candidate: false,
    leavesScope: false,
    record: source.record,
  };
  const seen = new Set([recordItemId(source.record)]);
  const listed = [root];
  for (const member of source.members) {
    const id = recordItemId(member.record);
    if (seen.has(id) || !ROOT_KINDS.has(member.record.kind)) {
      continue;
    }
    seen.add(id);
    if (!previous) {
      if (member.matchesFilter(currentValues(member.record))) {
        listed.push({
          candidate: false,
          leavesScope: false,
          record: member.record,
        });
      }
    } else if (previous.has(id)) {
      const inScope = member.matchesFilter(
        approvedViewValues(member.record, previous),
      );
      listed.push({
        candidate: false,
        leavesScope: !inScope,
        record: member.record,
      });
    } else if (member.matchesFilter(currentValues(member.record))) {
      listed.push({
        candidate: true,
        leavesScope: false,
        record: member.record,
      });
    }
  }
  return listed;
}

function stateOf(
  previous: Map<string, ShareManifestItem> | null,
  itemId: string,
  value: string | null,
): ShareItem["state"] {
  if (!previous) {
    return null;
  }
  const approved = previous.get(itemId);
  if (!approved) {
    return "Never approved";
  }
  return approved.live || approved.value === value
    ? "Approved"
    : "Changed since approval";
}

function buildScope(
  source: ShareSource,
  previous: Map<string, ShareManifestItem> | null,
): ScopeModel {
  const listed = listRecords(source, previous);
  const recordIds = new Map(
    listed
      .filter((entry) => !entry.leavesScope)
      .map((entry) => [`${entry.record.kind}:${entry.record.id}`, entry]),
  );
  const items: ShareItem[] = [];
  const relationTargets = new Map<string, string>();
  const fieldKeys = new Map<string, string>();
  for (const { candidate, leavesScope, record } of listed) {
    const parentId = recordItemId(record);
    items.push({
      candidate,
      group: null,
      itemId: parentId,
      kind: "Record",
      label: `${record.kind}: ${record.title}`,
      live: false,
      leavesScope,
      liveEligible: false,
      parentId: null,
      selectable: !leavesScope,
      state: stateOf(previous, parentId, null),
      value: null,
    });
    for (const field of fieldsOf(record)) {
      const itemId = fieldItemId(record, field.key);
      fieldKeys.set(itemId, field.key);
      items.push({
        candidate: false,
        group: null,
        itemId,
        kind: "Field",
        label: field.label,
        live: previous?.get(itemId)?.live ?? false,
        leavesScope: false,
        liveEligible: isLiveEligible(field.kind),
        parentId,
        selectable: !leavesScope,
        state: stateOf(previous, itemId, field.value),
        value: field.value,
      });
    }
    for (const part of record.parts) {
      const itemId = partItemId(record, part);
      const target = part.target
        ? recordIds.get(`${part.target.kind}:${part.target.id}`)
        : undefined;
      if (part.kind === "Relation" && target) {
        relationTargets.set(itemId, recordItemId(target.record));
      }
      items.push({
        candidate: false,
        group: part.group ?? null,
        itemId,
        kind: part.kind,
        label: part.label,
        live: false,
        leavesScope: false,
        liveEligible: false,
        parentId,
        selectable: !leavesScope && (part.kind !== "Relation" || !!target),
        state: stateOf(previous, itemId, part.detail),
        value: part.detail,
      });
    }
  }
  return { fieldKeys, items, relationTargets };
}

function placeholderFindings(
  source: ShareSource,
  scope: ScopeModel,
): PlaceholderFinding[] {
  const records = new Map(
    [source.record, ...source.members.map((member) => member.record)].map(
      (record) => [recordItemId(record), record],
    ),
  );
  const findings: PlaceholderFinding[] = [];
  for (const item of scope.items) {
    const record = item.parentId ? records.get(item.parentId) : undefined;
    // Fields and non-record part texts (for example a diagram's origin
    // snapshot text) are checked alike: the rule is about the text itself.
    if (item.kind === "Record" || !record || !item.value) {
      continue;
    }
    for (const match of findPlaceholders(item.value)) {
      findings.push({
        context: match.context,
        fieldKey: scope.fieldKeys.get(item.itemId) ?? "",
        fieldLabel: item.label,
        itemId: item.itemId,
        placeholder: match.placeholder,
        recordId: record.id,
        recordKind: record.kind,
        recordTitle: record.title,
      });
    }
  }
  return findings;
}

function previousOf(surface: StoredShareSurface | null) {
  return surface
    ? new Map(surface.manifest.items.map((item) => [item.itemId, item]))
    : null;
}

function diffOf(
  previous: Map<string, ShareManifestItem> | null,
  items: ShareItem[],
): ShareDiff | null {
  if (!previous) {
    return null;
  }
  const current = new Set(items.map((item) => item.itemId));
  return {
    added: items
      .filter((item) => item.state === "Never approved")
      .map((item) => item.itemId),
    changed: items
      .filter((item) => item.state === "Changed since approval")
      .map((item) => item.itemId),
    removed: [...previous.keys()].filter((id) => !current.has(id)),
  };
}

const isExpired = (expiresAt: Date | null, at: Date) =>
  expiresAt !== null && expiresAt <= at;

function summaryOf(
  surface: StoredShareSurface | null,
  at: Date,
): ShareSurfaceSummary | null {
  return surface
    ? {
        expiresAt: surface.expiresAt?.toISOString() ?? null,
        label: surface.manifest.label,
        lastApprovedAt: surface.approvedAt,
        passwordProtected: surface.passwordProtected,
        revision: surface.revision,
        state: isExpired(surface.expiresAt, at) ? "Expired" : "Active",
        surfaceId: surface.surfaceId,
      }
    : null;
}

const actorAliasOf = (accountId: string) =>
  `account:${sha256Hex(accountId).slice(0, 16)}`;

function fingerprintOf(input: ApproveShareScopeInput) {
  const canonical = JSON.stringify({
    approved: [...input.approvedItemIds].sort(),
    live: [...input.liveItemIds].sort(),
    publishAnyway: input.publishAnyway,
    root: input.root,
    surfaceId: input.surfaceId ?? null,
  });
  return sha256Hex(canonical);
}

function checkApprovedItem(
  scope: ScopeModel,
  approved: Set<string>,
  item: ShareItem | undefined,
) {
  if (!item) {
    throw new LinkSharingScopeError(
      "The selection no longer matches the preview. Preview the scope again.",
    );
  }
  if (!item.selectable) {
    throw new LinkSharingScopeError(`${item.label} cannot be approved.`);
  }
  if (item.parentId && !approved.has(item.parentId)) {
    throw new LinkSharingScopeError(
      `${item.label} needs its record in the scope.`,
    );
  }
  const target = scope.relationTargets.get(item.itemId);
  if (item.kind === "Relation" && !(target && approved.has(target))) {
    throw new LinkSharingScopeError(
      `${item.label} needs its other end in the scope.`,
    );
  }
}

/** Every exclusive group of an approved record has exactly one approved item. */
function checkExclusiveGroups(scope: ScopeModel, approved: Set<string>) {
  const groups = new Map<string, number>();
  for (const item of scope.items) {
    if (item.group && item.parentId && approved.has(item.parentId)) {
      const key = `${item.parentId}|${item.group}`;
      groups.set(
        key,
        (groups.get(key) ?? 0) + (approved.has(item.itemId) ? 1 : 0),
      );
    }
  }
  for (const [key, count] of groups) {
    if (count !== 1) {
      throw new LinkSharingScopeError(
        `Choose exactly one ${key.split("|")[1]}.`,
      );
    }
  }
}

/** Explicit selection against the fresh preview; nothing is approved by default. */
function validateSelection(
  scope: ScopeModel,
  approved: Set<string>,
  live: Set<string>,
  root: ShareRoot,
) {
  const byId = new Map(scope.items.map((item) => [item.itemId, item]));
  for (const id of approved) {
    checkApprovedItem(scope, approved, byId.get(id));
  }
  if (!approved.has(`record:${root.kind}:${root.id}`)) {
    throw new LinkSharingScopeError("The shared record must be approved.");
  }
  checkExclusiveGroups(scope, approved);
  for (const id of live) {
    const item = byId.get(id);
    if (
      !(item && approved.has(id) && item.kind === "Field" && item.liveEligible)
    ) {
      throw new LinkSharingScopeError(
        "Only an approved field on the live allow-list can be marked Live.",
      );
    }
  }
}

export function createLinkSharing(
  store: LinkSharingStore,
  options: {
    /** `Denetim kaydı` entries; also the share start and revoke rate limit. */
    audit?: LinkSharingAudit;
    events?: LinkSharingSecurityEvents;
    hasher?: LinkPasswordHasher;
    now?: () => Date;
  } = {},
): LinkSharingAccess {
  const now = options.now ?? (() => new Date());
  const hasher = options.hasher ?? scryptLinkPasswordHasher;

  async function load(accountId: string, input: PreviewShareScopeInput) {
    const source = await store.source(accountId, input.root);
    if (!source) {
      return null;
    }
    const surface = await store.surface(accountId, input.root, input.surfaceId);
    if (input.surfaceId && !surface) {
      return null;
    }
    const previous = previousOf(surface);
    return { previous, scope: buildScope(source, previous), source, surface };
  }

  async function preview(
    accountId: string,
    rawInput: PreviewShareScopeInput,
  ): Promise<ShareScopePreview | null> {
    const input = previewShareScopeInputSchema.parse(rawInput);
    const loaded = await load(accountId, input);
    if (!loaded) {
      return null;
    }
    const { previous, scope, source, surface } = loaded;
    return {
      blockers: source.blockers,
      diff: diffOf(previous, scope.items),
      items: scope.items,
      placeholders: placeholderFindings(source, scope),
      projectId: source.projectId,
      root: {
        id: source.record.id,
        kind: input.root.kind,
        title: source.record.title,
      },
      surface: summaryOf(surface, now()),
    };
  }

  async function approve(
    accountId: string,
    rawInput: ApproveShareScopeInput,
  ): Promise<ApprovedShare | null> {
    const input = approveShareScopeInputSchema.parse(rawInput);
    const fingerprint = fingerprintOf(input);
    const replay = await store.findApproval(accountId, input.approvalId);
    if (replay) {
      if (replay.fingerprint !== fingerprint) {
        throw new LinkSharingConflictError(input.approvalId);
      }
      return replay.result;
    }
    const loaded = await load(accountId, input);
    if (!loaded) {
      return null;
    }
    const { scope, source, surface } = loaded;
    if (source.blockers.length > 0) {
      throw new LinkSharingScopeError(source.blockers.join(" "));
    }
    const approved = new Set(input.approvedItemIds);
    const live = new Set(input.liveItemIds);
    validateSelection(scope, approved, live, input.root);
    const findings = placeholderFindings(source, scope).filter((finding) =>
      approved.has(finding.itemId),
    );
    if (findings.length > 0 && !input.publishAnyway) {
      throw new LinkSharingPlaceholdersError(findings);
    }
    const newSurfaceId = crypto.randomUUID();
    if (!surface) {
      // The reservation lands before the store commit: a store failure keeps
      // the slot, so the limit is never bypassed by concurrent attempts.
      await reserveRateLimit(
        accountId,
        "link-sharing.share-created",
        input.approvalId,
        newSurfaceId,
      );
    }
    const items: ShareManifestItem[] = scope.items
      .filter((item) => approved.has(item.itemId))
      .map((item) => ({
        itemId: item.itemId,
        kind: item.kind,
        label: item.label,
        live: live.has(item.itemId),
        parentId: item.parentId,
        value: item.value,
      }));
    const approvedAt = now().toISOString();
    const token = surface ? null : randomSecret();
    const manifest: ShareManifest = {
      approvedAt,
      format: SHARE_MANIFEST_FORMAT,
      items,
      label: shareLabel(live.size, items.length - live.size),
      placeholdersAcknowledged: findings.length > 0,
      root: input.root,
      version: 1,
    };
    const approvedShare = await store.commit({
      accountId,
      approvalId: input.approvalId,
      fingerprint,
      manifest,
      newSurfaceId,
      placeholdersAcknowledged: findings.length > 0,
      projectId: source.projectId,
      root: input.root,
      surfaceId: surface?.surfaceId ?? null,
      tokenHash: token ? sha256Hex(token) : null,
    });
    return finishApproval(approvedShare, newSurfaceId, token);
  }

  /** A new surface returns its token once. The audit entry was the reservation. */
  function finishApproval(
    approvedShare: ApprovedShare | null,
    newSurfaceId: string,
    token: string | null,
  ) {
    return approvedShare && approvedShare.surfaceId === newSurfaceId
      ? { ...approvedShare, accessToken: token }
      : approvedShare;
  }

  /**
   * The founder's start and revoke writes are rate-limited by reserving the
   * slot as the audit entry itself: one reservation per attempt id inside a
   * per-actor serialized transaction, so a concurrent burst cannot pass the
   * check together and a retried or event-log-failed write never loses its
   * entry. A write that fails after a successful reservation keeps the slot
   * (fail-closed; the audit alias and target never carry a secret).
   */
  async function reserveRateLimit(
    accountId: string,
    type: LinkSharingAuditType,
    idKey: string,
    targetAlias: string,
  ): Promise<void> {
    if (!options.audit) {
      return;
    }
    const at = now();
    const reserved = await options.audit.reserve({
      actorAlias: actorAliasOf(accountId),
      counted:
        type === "link-sharing.share-revoked"
          ? SHARE_REVOKE_TYPES
          : SHARE_START_TYPES,
      id: `${type}:${sha256Hex(`${accountId}\u0000${idKey}`).slice(0, 32)}`,
      limit: SHARE_CHANGE_LIMIT,
      occurredAt: at,
      since: new Date(at.getTime() - SHARE_CHANGE_WINDOW_MS),
      targetAlias,
      type,
    });
    if (!reserved) {
      throw new LinkSharingRateLimitError(SHARE_CHANGE_WINDOW_MS / 1000);
    }
  }

  /** A secret-free `Denetim kaydı` entry: alias, surface id, type, time. */
  async function record(
    type: LinkSharingAuditType,
    accountId: string,
    surfaceId: string,
  ) {
    await options.audit?.append({
      actorAlias: actorAliasOf(accountId),
      id: `${type}:${crypto.randomUUID()}`,
      occurredAt: now(),
      targetAlias: surfaceId,
      type,
    });
  }

  async function appendEvents(
    accountId: string,
    surfaceId: string,
    accessEpoch: number,
    types: ShareAccessEvent["type"][],
  ) {
    await Promise.all(
      types.map((type) =>
        options.events?.append({
          accessEpoch,
          actor: actorAliasOf(accountId),
          occurredAt: now(),
          surfaceId,
          type,
        }),
      ),
    );
  }

  /**
   * Applies a revoke, password or token change together with its security
   * events. The events live in a separate irreversible log, so the two writes
   * cannot share a transaction. Ordering, safest first:
   * 1. Append the events for the epoch the change will produce. The event id
   *    is derived from the epoch, so a repeated append never duplicates, and an
   *    event without its change only makes a restore replay cancel the row
   *    (fail closed).
   * 2. Apply the change even when step 1 failed: access must end now.
   * 3. When step 1 failed, or the real epoch differs, append again with the
   *    real epoch; if that fails too, throw instead of reporting success, so
   *    the unlogged change is never silent.
   */
  async function changeWithEvents<T extends { accessEpoch: number }>(
    accountId: string,
    surfaceId: string,
    types: ShareAccessEvent["type"][],
    change: () => Promise<T | null>,
  ): Promise<T | null> {
    const state = await store.lifecycle(accountId, surfaceId);
    if (!state) {
      return null;
    }
    const predicted = state.accessEpoch + 1;
    let logged = true;
    try {
      await appendEvents(accountId, surfaceId, predicted, types);
    } catch {
      logged = false;
    }
    const changed = await change();
    if (!changed) {
      return null;
    }
    if (!logged || changed.accessEpoch !== predicted) {
      try {
        await appendEvents(accountId, surfaceId, changed.accessEpoch, types);
      } catch (cause) {
        throw new LinkSharingEventLogError(
          "The change took effect, but its security event could not be logged. Try again.",
          { cause },
        );
      }
    }
    return changed;
  }

  /** Future instants only; `null` removes the expiry. */
  function checkedExpiry(expiresAt: string | null) {
    if (expiresAt === null) {
      return null;
    }
    const at = new Date(expiresAt);
    if (at <= now()) {
      throw new LinkSharingStateError("Choose an expiry in the future.");
    }
    return at;
  }

  const expiryOf = (
    surfaceId: string,
    expiresAt: Date | null,
  ): ShareExpiry => ({
    expiresAt: expiresAt?.toISOString() ?? null,
    state: isExpired(expiresAt, now()) ? "Expired" : "Active",
    surfaceId,
  });

  async function setExpiry(
    accountId: string,
    rawInput: SetShareExpiryInput,
  ): Promise<ShareExpiry | null> {
    const input = setShareExpiryInputSchema.parse(rawInput);
    const lifecycle = await store.lifecycle(accountId, input.surfaceId);
    if (!lifecycle) {
      return null;
    }
    // Extending is for a link that has not expired; an expired one is either
    // reopened (with confirmation) or reshared.
    if (isExpired(lifecycle.expiresAt, now())) {
      throw new LinkSharingStateError(
        "This link has expired. Reopen the same link or reshare with a new link.",
      );
    }
    const expiresAt = checkedExpiry(input.expiresAt);
    const changed = await store.updateExpiry(
      accountId,
      input.surfaceId,
      expiresAt,
      false,
    );
    if (!changed) {
      return null;
    }
    await record("link-sharing.expiry-changed", accountId, input.surfaceId);
    return expiryOf(input.surfaceId, expiresAt);
  }

  async function reopen(
    accountId: string,
    rawInput: ReopenExpiredLinkInput,
  ): Promise<ShareExpiry | null> {
    const input = reopenExpiredLinkInputSchema.parse(rawInput);
    const lifecycle = await store.lifecycle(accountId, input.surfaceId);
    if (!lifecycle) {
      return null;
    }
    if (!isExpired(lifecycle.expiresAt, now())) {
      throw new LinkSharingStateError("Only an expired link can be reopened.");
    }
    const expiresAt = checkedExpiry(input.expiresAt);
    // Sessions minted before the expiry must not wake up with the link.
    const changed = await store.updateExpiry(
      accountId,
      input.surfaceId,
      expiresAt,
      true,
    );
    if (!changed) {
      return null;
    }
    await appendEvents(accountId, input.surfaceId, changed.accessEpoch, [
      "link-sharing.sessions-revoked",
    ]);
    await record("link-sharing.share-reopened", accountId, input.surfaceId);
    return expiryOf(input.surfaceId, expiresAt);
  }

  async function reshare(
    accountId: string,
    rawInput: ReshareExpiredLinkInput,
  ): Promise<ApprovedShare | null> {
    const input = reshareExpiredLinkInputSchema.parse(rawInput);
    const lifecycle = await store.lifecycle(accountId, input.surfaceId);
    if (!lifecycle) {
      return null;
    }
    if (!isExpired(lifecycle.expiresAt, now())) {
      throw new LinkSharingStateError(
        "Only an expired link can be reshared with a new link.",
      );
    }
    const expiresAt = checkedExpiry(input.expiresAt);
    await reserveRateLimit(
      accountId,
      "link-sharing.share-reshared",
      input.newSurfaceId,
      input.surfaceId,
    );
    const token = randomSecret();
    const shared = await store.reshare({
      accountId,
      expiresAt,
      newSurfaceId: input.newSurfaceId,
      sourceSurfaceId: input.surfaceId,
      tokenHash: sha256Hex(token),
    });
    if (!shared) {
      return null;
    }
    // A retried `newSurfaceId` answers without a token; the first answer held it.
    if (!shared.created) {
      return shared.share;
    }
    // The audit entry was the rate-limit reservation.
    return { ...shared.share, accessToken: token };
  }

  async function revoke(
    accountId: string,
    rawInput: RevokeShareInput,
  ): Promise<RevokedShare | null> {
    const input = revokeShareInputSchema.parse(rawInput);
    await reserveRateLimit(
      accountId,
      "link-sharing.share-revoked",
      input.surfaceId,
      input.surfaceId,
    );
    const at = now();
    const revoked = await changeWithEvents(
      accountId,
      input.surfaceId,
      ["link-sharing.surface-revoked", "link-sharing.sessions-revoked"],
      () => store.revoke(accountId, input.surfaceId, at),
    );
    if (!revoked) {
      return null;
    }
    // The audit entry was the rate-limit reservation; a change whose security
    // event failed already wrote it, so the revoked write is never uncounted.
    return { revokedAt: at.toISOString(), surfaceId: input.surfaceId };
  }

  async function changeAccess(
    accountId: string,
    surfaceId: string,
    patch: ShareAccessPatch,
    type: ShareAccessEvent["type"],
  ) {
    // Secret-free events: an aliased actor, the surface id and the epoch only.
    const changed = await changeWithEvents(
      accountId,
      surfaceId,
      [type, "link-sharing.sessions-revoked"],
      () => store.updateAccess(accountId, surfaceId, patch),
    );
    if (!changed) {
      return null;
    }
    await record(
      type === "link-sharing.token-rotated"
        ? "link-sharing.token-rotated"
        : "link-sharing.password-rotated",
      accountId,
      surfaceId,
    );
    return changed;
  }

  return {
    approve,
    preview,
    reopen,
    reshare,
    revoke,
    setExpiry,
    roots(accountId, projectId) {
      return store.roots(
        accountId,
        shareRootsInputSchema.parse({ projectId }).projectId,
      );
    },
    async rotateToken(
      accountId: string,
      rawInput: RotateShareTokenInput,
    ): Promise<ShareAccess | null> {
      const input = rotateShareTokenInputSchema.parse(rawInput);
      const token = randomSecret();
      const changed = await changeAccess(
        accountId,
        input.surfaceId,
        { tokenHash: sha256Hex(token) },
        "link-sharing.token-rotated",
      );
      return changed
        ? {
            passwordProtected: changed.passwordProtected,
            surfaceId: input.surfaceId,
            token,
          }
        : null;
    },
    async setPassword(
      accountId: string,
      rawInput: SetLinkPasswordInput,
    ): Promise<ShareAccess | null> {
      const input = setLinkPasswordInputSchema.parse(rawInput);
      const passwordHash =
        input.password === null ? null : await hasher.hash(input.password);
      const changed = await changeAccess(
        accountId,
        input.surfaceId,
        { passwordHash },
        "link-sharing.password-changed",
      );
      return changed
        ? {
            passwordProtected: changed.passwordProtected,
            surfaceId: input.surfaceId,
            token: null,
          }
        : null;
    },
  };
}

/**
 * Link Sharing behavior (spec 73, #482). The closed world is built only from
 * what the source port hands over for the chosen root: the root record, the
 * members a collection root names, and the parts of those records. Nothing is
 * inherited through a folder, parent, relation or view. Approval re-derives
 * the preview, checks the founder's explicit selection against it and writes
 * one immutable manifest revision through the store.
 */

export interface ShareSourceField {
  key: string;
  kind: ShareFieldKind;
  label: string;
  value: string | null;
}

/** A non-field part of a record: version, attachment, embed, relation, layout. */
export interface ShareSourcePart {
  detail: string | null;
  /** Exactly one part of a group must be approved (a version, a view). */
  group?: string;
  id: string;
  kind: Exclude<ShareItemKind, "Field" | "Record">;
  label: string;
  /** A relation's other end; approvable only when that record is itself in scope. */
  target?: { id: string; kind: string };
}

export interface ShareSourceRecord {
  fields: ShareSourceField[];
  id: string;
  /** A main record kind; anything else (an Inbox item, a Draft) is dropped. */
  kind: string;
  parts: ShareSourcePart[];
  title: string;
}

export interface ShareSourceMember {
  /** Whether the record belongs to the collection filter for these values. */
  matchesFilter: (values: Record<string, string | null>) => boolean;
  record: ShareSourceRecord;
}

export interface ShareSource {
  /** Reasons no link can be approved yet, such as no exact version to pick. */
  blockers: string[];
  /** Filter pool of a collection root; empty for every other root. */
  members: ShareSourceMember[];
  projectId: string;
  record: ShareSourceRecord;
}

export interface StoredShareSurface {
  approvedAt: string;
  manifest: ShareManifest;
  revision: number;
  surfaceId: string;
}

export interface ShareApprovalCommit {
  accountId: string;
  approvalId: string;
  fingerprint: string;
  manifest: ShareManifest;
  /** Generated by the behavior so memory and database stores agree. */
  newSurfaceId: string;
  placeholdersAcknowledged: boolean;
  projectId: string;
  root: ShareRoot;
  /** `null` creates the Dış yüzey; otherwise a revision joins that surface. */
  surfaceId: string | null;
}

/** Port to the source records and the stored surfaces; no member rewrites a revision. */
export interface LinkSharingStore {
  commit: (commit: ShareApprovalCommit) => Promise<ApprovedShare | null>;
  findApproval: (
    accountId: string,
    approvalId: string,
  ) => Promise<{ fingerprint: string; result: ApprovedShare } | null>;
  roots: (
    accountId: string,
    projectId: string,
  ) => Promise<ShareRootSummary[] | null>;
  source: (accountId: string, root: ShareRoot) => Promise<ShareSource | null>;
  /** The given surface of the root, else its latest uncancelled one. */
  surface: (
    accountId: string,
    root: ShareRoot,
    surfaceId?: string,
  ) => Promise<StoredShareSurface | null>;
}

interface ScopeModel {
  /** Field item id to its field key. */
  fieldKeys: Map<string, string>;
  items: ShareItem[];
  /** Relation item id to the Record item id it points at, when in scope. */
  relationTargets: Map<string, string>;
}

const ROOT_KINDS = new Set<string>(LINK_SHARING_ROOT_KINDS);
const recordItemId = (record: ShareSourceRecord) =>
  `record:${record.kind}:${record.id}`;
const fieldItemId = (record: ShareSourceRecord, key: string) =>
  `field:${record.kind}:${record.id}:${key}`;
const partItemId = (record: ShareSourceRecord, part: ShareSourcePart) =>
  `part:${record.kind}:${record.id}:${part.id}`;

function fieldsOf(record: ShareSourceRecord): ShareSourceField[] {
  const fields = record.fields.filter((field) => !isSecretKind(field.kind));
  return fields.some((field) => field.key === "title")
    ? fields
    : [
        { key: "title", kind: "title", label: "Title", value: record.title },
        ...fields,
      ];
}

/**
 * Values the visitor would see for these fields now: frozen fields keep their
 * approved value, `Live` fields follow the source. Used for membership only.
 */
function approvedViewValues(
  record: ShareSourceRecord,
  previous: Map<string, ShareManifestItem>,
) {
  const values: Record<string, string | null> = {};
  for (const field of fieldsOf(record)) {
    const approved = previous.get(fieldItemId(record, field.key));
    values[field.key] =
      approved && !approved.live ? approved.value : field.value;
  }
  return values;
}

function currentValues(record: ShareSourceRecord) {
  return Object.fromEntries(
    fieldsOf(record).map((field) => [field.key, field.value]),
  );
}

interface ListedRecord {
  candidate: boolean;
  leavesScope: boolean;
  record: ShareSourceRecord;
}

/**
 * A new filter match is only a candidate on the owner's diff. An approved
 * member leaves only when the values the visitor sees (frozen, with `Live`
 * fields current) no longer match; any other edit never shrinks the scope.
 */
function listRecords(
  source: ShareSource,
  previous: Map<string, ShareManifestItem> | null,
): ListedRecord[] {
  const root: ListedRecord = {
    candidate: false,
    leavesScope: false,
    record: source.record,
  };
  const seen = new Set([recordItemId(source.record)]);
  const listed = [root];
  for (const member of source.members) {
    const id = recordItemId(member.record);
    if (seen.has(id) || !ROOT_KINDS.has(member.record.kind)) {
      continue;
    }
    seen.add(id);
    if (!previous) {
      if (member.matchesFilter(currentValues(member.record))) {
        listed.push({
          candidate: false,
          leavesScope: false,
          record: member.record,
        });
      }
    } else if (previous.has(id)) {
      const inScope = member.matchesFilter(
        approvedViewValues(member.record, previous),
      );
      listed.push({
        candidate: false,
        leavesScope: !inScope,
        record: member.record,
      });
    } else if (member.matchesFilter(currentValues(member.record))) {
      listed.push({
        candidate: true,
        leavesScope: false,
        record: member.record,
      });
    }
  }
  return listed;
}

function stateOf(
  previous: Map<string, ShareManifestItem> | null,
  itemId: string,
  value: string | null,
): ShareItem["state"] {
  if (!previous) {
    return null;
  }
  const approved = previous.get(itemId);
  if (!approved) {
    return "Never approved";
  }
  return approved.live || approved.value === value
    ? "Approved"
    : "Changed since approval";
}

function buildScope(
  source: ShareSource,
  previous: Map<string, ShareManifestItem> | null,
): ScopeModel {
  const listed = listRecords(source, previous);
  const recordIds = new Map(
    listed
      .filter((entry) => !entry.leavesScope)
      .map((entry) => [`${entry.record.kind}:${entry.record.id}`, entry]),
  );
  const items: ShareItem[] = [];
  const relationTargets = new Map<string, string>();
  const fieldKeys = new Map<string, string>();
  for (const { candidate, leavesScope, record } of listed) {
    const parentId = recordItemId(record);
    items.push({
      candidate,
      group: null,
      itemId: parentId,
      kind: "Record",
      label: `${record.kind}: ${record.title}`,
      live: false,
      leavesScope,
      liveEligible: false,
      parentId: null,
      selectable: !leavesScope,
      state: stateOf(previous, parentId, null),
      value: null,
    });
    for (const field of fieldsOf(record)) {
      const itemId = fieldItemId(record, field.key);
      fieldKeys.set(itemId, field.key);
      items.push({
        candidate: false,
        group: null,
        itemId,
        kind: "Field",
        label: field.label,
        live: previous?.get(itemId)?.live ?? false,
        leavesScope: false,
        liveEligible: isLiveEligible(field.kind),
        parentId,
        selectable: !leavesScope,
        state: stateOf(previous, itemId, field.value),
        value: field.value,
      });
    }
    for (const part of record.parts) {
      const itemId = partItemId(record, part);
      const target = part.target
        ? recordIds.get(`${part.target.kind}:${part.target.id}`)
        : undefined;
      if (part.kind === "Relation" && target) {
        relationTargets.set(itemId, recordItemId(target.record));
      }
      items.push({
        candidate: false,
        group: part.group ?? null,
        itemId,
        kind: part.kind,
        label: part.label,
        live: false,
        leavesScope: false,
        liveEligible: false,
        parentId,
        selectable: !leavesScope && (part.kind !== "Relation" || !!target),
        state: stateOf(previous, itemId, part.detail),
        value: part.detail,
      });
    }
  }
  return { fieldKeys, items, relationTargets };
}

function placeholderFindings(
  source: ShareSource,
  scope: ScopeModel,
): PlaceholderFinding[] {
  const records = new Map(
    [source.record, ...source.members.map((member) => member.record)].map(
      (record) => [recordItemId(record), record],
    ),
  );
  const findings: PlaceholderFinding[] = [];
  for (const item of scope.items) {
    const record = item.parentId ? records.get(item.parentId) : undefined;
    if (item.kind !== "Field" || !record || !item.value) {
      continue;
    }
    for (const match of findPlaceholders(item.value)) {
      findings.push({
        context: match.context,
        fieldKey: scope.fieldKeys.get(item.itemId) ?? "",
        fieldLabel: item.label,
        itemId: item.itemId,
        placeholder: match.placeholder,
        recordId: record.id,
        recordKind: record.kind,
        recordTitle: record.title,
      });
    }
  }
  return findings;
}

function previousOf(surface: StoredShareSurface | null) {
  return surface
    ? new Map(surface.manifest.items.map((item) => [item.itemId, item]))
    : null;
}

function diffOf(
  previous: Map<string, ShareManifestItem> | null,
  items: ShareItem[],
): ShareDiff | null {
  if (!previous) {
    return null;
  }
  const current = new Set(items.map((item) => item.itemId));
  return {
    added: items
      .filter((item) => item.state === "Never approved")
      .map((item) => item.itemId),
    changed: items
      .filter((item) => item.state === "Changed since approval")
      .map((item) => item.itemId),
    removed: [...previous.keys()].filter((id) => !current.has(id)),
  };
}

function summaryOf(
  surface: StoredShareSurface | null,
): ShareSurfaceSummary | null {
  return surface
    ? {
        label: surface.manifest.label,
        lastApprovedAt: surface.approvedAt,
        revision: surface.revision,
        surfaceId: surface.surfaceId,
      }
    : null;
}

async function fingerprintOf(input: ApproveShareScopeInput) {
  const canonical = JSON.stringify({
    approved: [...input.approvedItemIds].sort(),
    live: [...input.liveItemIds].sort(),
    publishAnyway: input.publishAnyway,
    root: input.root,
    surfaceId: input.surfaceId ?? null,
  });
  const digest = await crypto.subtle.digest(
    "SHA-256",
    new TextEncoder().encode(canonical),
  );
  return [...new Uint8Array(digest)]
    .map((byte) => byte.toString(16).padStart(2, "0"))
    .join("");
}

function checkApprovedItem(
  scope: ScopeModel,
  approved: Set<string>,
  item: ShareItem | undefined,
) {
  if (!item) {
    throw new LinkSharingScopeError(
      "The selection no longer matches the preview. Preview the scope again.",
    );
  }
  if (!item.selectable) {
    throw new LinkSharingScopeError(`${item.label} cannot be approved.`);
  }
  if (item.parentId && !approved.has(item.parentId)) {
    throw new LinkSharingScopeError(
      `${item.label} needs its record in the scope.`,
    );
  }
  const target = scope.relationTargets.get(item.itemId);
  if (item.kind === "Relation" && !(target && approved.has(target))) {
    throw new LinkSharingScopeError(
      `${item.label} needs its other end in the scope.`,
    );
  }
}

/** Every exclusive group of an approved record has exactly one approved item. */
function checkExclusiveGroups(scope: ScopeModel, approved: Set<string>) {
  const groups = new Map<string, number>();
  for (const item of scope.items) {
    if (item.group && item.parentId && approved.has(item.parentId)) {
      const key = `${item.parentId}|${item.group}`;
      groups.set(
        key,
        (groups.get(key) ?? 0) + (approved.has(item.itemId) ? 1 : 0),
      );
    }
  }
  for (const [key, count] of groups) {
    if (count !== 1) {
      throw new LinkSharingScopeError(
        `Choose exactly one ${key.split("|")[1]}.`,
      );
    }
  }
}

/** Explicit selection against the fresh preview; nothing is approved by default. */
function validateSelection(
  scope: ScopeModel,
  approved: Set<string>,
  live: Set<string>,
  root: ShareRoot,
) {
  const byId = new Map(scope.items.map((item) => [item.itemId, item]));
  for (const id of approved) {
    checkApprovedItem(scope, approved, byId.get(id));
  }
  if (!approved.has(`record:${root.kind}:${root.id}`)) {
    throw new LinkSharingScopeError("The shared record must be approved.");
  }
  checkExclusiveGroups(scope, approved);
  for (const id of live) {
    const item = byId.get(id);
    if (
      !(item && approved.has(id) && item.kind === "Field" && item.liveEligible)
    ) {
      throw new LinkSharingScopeError(
        "Only an approved field on the live allow-list can be marked Live.",
      );
    }
  }
}

export function createLinkSharing(
  store: LinkSharingStore,
  options: { now?: () => Date } = {},
): LinkSharingAccess {
  const now = options.now ?? (() => new Date());

  async function load(accountId: string, input: PreviewShareScopeInput) {
    const source = await store.source(accountId, input.root);
    if (!source) {
      return null;
    }
    const surface = await store.surface(accountId, input.root, input.surfaceId);
    if (input.surfaceId && !surface) {
      return null;
    }
    const previous = previousOf(surface);
    return { previous, scope: buildScope(source, previous), source, surface };
  }

  async function preview(
    accountId: string,
    rawInput: PreviewShareScopeInput,
  ): Promise<ShareScopePreview | null> {
    const input = previewShareScopeInputSchema.parse(rawInput);
    const loaded = await load(accountId, input);
    if (!loaded) {
      return null;
    }
    const { previous, scope, source, surface } = loaded;
    return {
      blockers: source.blockers,
      diff: diffOf(previous, scope.items),
      items: scope.items,
      placeholders: placeholderFindings(source, scope),
      projectId: source.projectId,
      root: {
        id: source.record.id,
        kind: input.root.kind,
        title: source.record.title,
      },
      surface: summaryOf(surface),
    };
  }

  async function approve(
    accountId: string,
    rawInput: ApproveShareScopeInput,
  ): Promise<ApprovedShare | null> {
    const input = approveShareScopeInputSchema.parse(rawInput);
    const fingerprint = await fingerprintOf(input);
    const replay = await store.findApproval(accountId, input.approvalId);
    if (replay) {
      if (replay.fingerprint !== fingerprint) {
        throw new LinkSharingConflictError(input.approvalId);
      }
      return replay.result;
    }
    const loaded = await load(accountId, input);
    if (!loaded) {
      return null;
    }
    const { scope, source, surface } = loaded;
    if (source.blockers.length > 0) {
      throw new LinkSharingScopeError(source.blockers.join(" "));
    }
    const approved = new Set(input.approvedItemIds);
    const live = new Set(input.liveItemIds);
    validateSelection(scope, approved, live, input.root);
    const findings = placeholderFindings(source, scope).filter((finding) =>
      approved.has(finding.itemId),
    );
    if (findings.length > 0 && !input.publishAnyway) {
      throw new LinkSharingPlaceholdersError(findings);
    }
    const items: ShareManifestItem[] = scope.items
      .filter((item) => approved.has(item.itemId))
      .map((item) => ({
        itemId: item.itemId,
        kind: item.kind,
        label: item.label,
        live: live.has(item.itemId),
        parentId: item.parentId,
        value: item.value,
      }));
    const approvedAt = now().toISOString();
    const manifest: ShareManifest = {
      approvedAt,
      format: SHARE_MANIFEST_FORMAT,
      items,
      label: shareLabel(live.size, items.length - live.size),
      placeholdersAcknowledged: findings.length > 0,
      root: input.root,
      version: 1,
    };
    return store.commit({
      accountId,
      approvalId: input.approvalId,
      fingerprint,
      manifest,
      newSurfaceId: crypto.randomUUID(),
      placeholdersAcknowledged: findings.length > 0,
      projectId: source.projectId,
      root: input.root,
      surfaceId: surface?.surfaceId ?? null,
    });
  }

  return {
    approve,
    preview,
    roots(accountId, projectId) {
      return store.roots(
        accountId,
        shareRootsInputSchema.parse({ projectId }).projectId,
      );
    },
  };
}
